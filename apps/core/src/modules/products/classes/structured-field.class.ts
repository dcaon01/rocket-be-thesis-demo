import { ApiProperty } from "@nestjs/swagger";
import { TypeEnum } from "../enums/type.enum";

export class StructureField {
  /** Name of the field. */
  @ApiProperty({
    example: "fieldName",
    description: "The name of the field.",
  })
  name: string;

  /** Type of the field (e.g., string, number, boolean, object, array). */
  @ApiProperty({
    example: "string",
    description: "The type of the field.",
    enum: TypeEnum,
  })
  type: TypeEnum;

  /** Indicates if the field is required. */
  @ApiProperty({
    example: true,
    description: "Indicates if the field is required.",
  })
  required: boolean;

  /** Indicates if the field is an array. */
  @ApiProperty({
    example: false,
    description: "Indicates if the field is an array.",
  })
  array: boolean;

  /** Indicates if the field is generated by the product and should not be provided by the user. */
  @ApiProperty({
    example: false,
    description: "Indicates if the field is generated by the product.",
  })
  generated: boolean;

  /** Indicates if the field cannot be modified after creation. */
  @ApiProperty({
    example: false,
    description: "Indicates if the field cannot be modified after creation.",
  })
  notModifiable: boolean;

  /**
   * Constructor for StructureField.
   * @param name the name of the field.
   * @param type the type of the field.
   * @param required flag indicating if it is required.
   * @param array flag indicating if it is an array.
   * @param generated flag indicating if the field is system-generated.
   * @param notModifiable flag indicating if the field cannot be modified after creation.
   */
  constructor(name: string, type: TypeEnum, required: boolean, array: boolean, generated: boolean, notModifiable: boolean) {
    this.name = name;
    this.type = type;
    this.required = required;
    this.array = array;
    this.generated = generated;
    this.notModifiable = notModifiable;
  }
}